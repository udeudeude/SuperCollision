import assert from 'node:assert/strict';
import {COMMONS_SOURCE,freesoundLicenseFilter,openverseSourceFilter,durationSeconds,importedAudioMime,rejectMislabelledAudio,downloadProgressText,audioVariantFromResult} from '../sounds-discover-core.mjs';
assert.equal(COMMONS_SOURCE,'wikimedia_audio');
assert.equal(openverseSourceFilter('wikimedia'),'wikimedia_audio');
assert.equal(openverseSourceFilter('openverse'),'');
assert.equal(audioVariantFromResult({source:'freesound'},'openverse'),'compressed preview');
assert.equal(audioVariantFromResult({provider:'freesound'},'openverse'),'compressed preview');
assert.equal(audioVariantFromResult({},'freesound'),'compressed preview');
assert.equal(audioVariantFromResult({source:'wikimedia_audio'},'openverse'),'provider-supplied audio (original quality unverified)');
assert.equal(freesoundLicenseFilter({commercial:true,modification:true}),'license:("Attribution" OR "Creative Commons 0")');
assert.equal(freesoundLicenseFilter({modification:true}),'');
assert.equal(freesoundLicenseFilter({noAttribution:true}),'license:"Creative Commons 0"');
assert.equal(freesoundLicenseFilter({cc0Only:true,commercial:true}),'license:"Creative Commons 0"');
assert.equal(durationSeconds(123000,'openverse'),123);
assert.equal(durationSeconds(10.25,'freesound'),10.25);
assert.equal(durationSeconds(null,'openverse'),0);
assert.equal(durationSeconds('NaN','openverse'),0);
assert.equal(importedAudioMime('audio/ogg; charset=utf-8','https://example.com/audio'),'audio/ogg');
assert.equal(importedAudioMime('application/octet-stream','https://example.com/files/sound.wav?token=abc'),'audio/wav');
assert.equal(importedAudioMime('application/ogg','https://example.com/sound.ogg'),'audio/ogg');
assert.throws(()=>importedAudioMime('text/html','https://example.com/sound.mp3'),/instead of audio/);
assert.throws(()=>importedAudioMime('application/json','https://example.com/sound.mp3'),/instead of audio/);
assert.throws(()=>importedAudioMime('image/jpeg','https://example.com/sound.mp3'),/instead of audio/);
assert.doesNotThrow(()=>rejectMislabelledAudio(new Uint8Array([82,73,70,70,0,0,87,65,86,69])));
assert.throws(()=>rejectMislabelledAudio(new TextEncoder().encode('<html>Permission denied')),/error page instead of audio/);
assert.throws(()=>rejectMislabelledAudio(new TextEncoder().encode('{"error":"expired"}')),/error page instead of audio/);
assert.throws(()=>rejectMislabelledAudio(new TextEncoder().encode('{"status":"forbidden"}')),/error page instead of audio/);
assert.throws(()=>rejectMislabelledAudio(new TextEncoder().encode('[{"code":403}]')),/error page instead of audio/);
assert.throws(()=>rejectMislabelledAudio(new TextEncoder().encode('<!doctype html>Unavailable')),/error page instead of audio/);
assert.match(downloadProgressText(1048576,4194304),/1.00 of 4.00 MB/);
assert.match(downloadProgressText(524288),/0.50 MB received/);
console.log('Discover transfer integrity and progress checks passed');
console.log('Sounds discovery provider, duration and media-type tests passed');
