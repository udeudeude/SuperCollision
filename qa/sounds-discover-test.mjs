import assert from 'node:assert/strict';
import {COMMONS_SOURCE,freesoundLicenseFilter,openverseSourceFilter,durationSeconds,importedAudioMime} from '../sounds-discover-core.mjs';
assert.equal(COMMONS_SOURCE,'wikimedia_audio');
assert.equal(openverseSourceFilter('wikimedia'),'wikimedia_audio');
assert.equal(openverseSourceFilter('openverse'),'');
assert.equal(freesoundLicenseFilter({commercial:true,modification:true}),'license:("Attribution" OR "Creative Commons 0")');
assert.equal(freesoundLicenseFilter({modification:true}),'');
assert.equal(freesoundLicenseFilter({noAttribution:true}),'license:"Creative Commons 0"');
assert.equal(freesoundLicenseFilter({cc0Only:true,commercial:true}),'license:"Creative Commons 0"');
assert.equal(durationSeconds(123000,'openverse'),123);
assert.equal(durationSeconds(10.25,'freesound'),10.25);
assert.equal(durationSeconds(null,'openverse'),0);
assert.equal(durationSeconds('NaN','openverse'),0);
assert.equal(importedAudioMime('audio/ogg; charset=utf-8','https://example.com/audio'),'audio/ogg');
assert.equal(importedAudioMime('application/octet-stream','https://example.com/files/sound.wav?token=abc'),'audio/wav');
assert.equal(importedAudioMime('application/ogg','https://example.com/sound.ogg'),'audio/ogg');
assert.throws(()=>importedAudioMime('text/html','https://example.com/sound.mp3'),/instead of audio/);
assert.throws(()=>importedAudioMime('application/json','https://example.com/sound.mp3'),/instead of audio/);
assert.throws(()=>importedAudioMime('image/jpeg','https://example.com/sound.mp3'),/instead of audio/);
console.log('Sounds discovery provider, duration and media-type tests passed');
