import assert from 'node:assert/strict';
import {findChapterPhraseMatches,estimateChapterSeek,toggleExplorerFavorite} from '../librivox-text-locator.mjs';
const sample='Before, the SHADOWS fell. Then the shadows rose.\nAnd the shadows returned.';
const matches=findChapterPhraseMatches(sample,'THE shadows',{contextChars:12});
assert.equal(matches.length,3);
assert.equal(matches[0].match,'the SHADOWS');
assert.equal(matches[2].match,'the shadows');
assert(matches.every(x=>x.fraction>=0&&x.fraction<=1));
assert.deepEqual(findChapterPhraseMatches(sample,'the missing phrase'),[]);
assert.equal(findChapterPhraseMatches('naïve café','CAFÉ')[0].match,'café');
assert.equal(findChapterPhraseMatches(sample,'').length,0);
assert.equal(estimateChapterSeek({fraction:0.5,durationSeconds:120}).seconds,60);
const corrected=estimateChapterSeek({fraction:0.5,durationSeconds:120,anchors:[{fraction:0.4,seconds:80}]});
assert.equal(corrected.method,'anchor-informed');
assert(corrected.seconds>80);
assert.equal(estimateChapterSeek({fraction:0.2,durationSeconds:0}),null);
const reader=toggleExplorerFavorite([],{type:'reader',id:17,label:'Peter Yearsley'});
assert.equal(reader[0].id,'17');
assert.equal(toggleExplorerFavorite(reader,{type:'reader',id:'17'}).length,0);
assert.equal(toggleExplorerFavorite(reader,{type:'author',id:17,label:'Different Person'}).length,2);
console.log('LibriVox text locator: all checks passed');
