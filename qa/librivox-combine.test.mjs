import assert from 'node:assert/strict';
import {normalizePersonName,samePerson,workHasAuthor,recordingHasReader,sectionHasReader,filteredSections,matchingReaderCredits,selectLibriVoxEditions} from '../librivox-combine.mjs';
const author={id:'george-macdonald',name:'George MacDonald'};
const reader={id:'peter-yearsley',name:'Peter Yearsley'};
const alice={id:'alice',name:'Alice Brown'};
const book={id:'book-a',title:'Novel',authors:[author]};
const another={id:'book-b',title:'Other',authors:[alice]};
const yearsleyRecording={id:'read-1',narrators:[reader],librivox_id:123};
const otherRecording={id:'read-2',narrators:[alice],librivox_id:456};
assert.equal(normalizePersonName(' George  MacDonald! '),'george macdonald');
assert.equal(samePerson({id:'not-matching',name:'Peter Yearsley'},reader),true);
assert.equal(samePerson({name:'Peter'},reader),false);
assert.equal(workHasAuthor(book,author),true);
assert.equal(workHasAuthor(another,author),false);
assert.equal(recordingHasReader(yearsleyRecording,reader),true);
assert.equal(recordingHasReader(otherRecording,reader),false);
assert.equal(sectionHasReader({readers:[{reader_id:'167',display_name:'Peter Yearsley'}]},reader),true);
assert.equal(sectionHasReader({readers:[{reader_id:'43',display_name:'Alice Brown'}]},reader),false);
assert.equal(sectionHasReader({readers:[{reader_id:'167',display_name:'NOT Peter Yearsley'}]}, {...reader,librivoxId:'167'}),true);
assert.equal(sectionHasReader({readers:[]},reader),false);
const credits=[{work:book,recording:yearsleyRecording},{work:book,recording:otherRecording},{work:another,recording:yearsleyRecording}];
assert.equal(matchingReaderCredits(credits,author,reader).length,1);
assert.equal(matchingReaderCredits(credits,null,reader).length,2);
assert.equal(selectLibriVoxEditions({...book,recordings:[yearsleyRecording,otherRecording]},reader,['read-1']).length,1);
assert.equal(selectLibriVoxEditions({...book,recordings:[yearsleyRecording,otherRecording]},reader,['read-2']).length,0);
assert.deepEqual(filteredSections([{readers:[{display_name:'Alice Brown'}]},{readers:[{display_name:'Peter Yearsley'}]}],reader).length,1);
console.log('PASS combined LibriVox author/reader facets, chapter-level filtering and identity boundaries');